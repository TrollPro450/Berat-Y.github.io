    (function () {
        var panel = { ana: 'sekme-ana', nedir: 'sekme-nedir', ozellikler: 'sekme-ozellikler', sss: 'sekme-sss' };
        var anaBaslik = document.title;
        var baslik = { nedir: 'Meb Launcher Nedir? | Berat Y.', ozellikler: 'Meb Launcher Özellikleri | Berat Y.', sss: 'Meb Launcher SSS | Berat Y.' };
        function ac(ad, hashYaz) {
            if (!panel[ad]) ad = 'ana';
            Object.keys(panel).forEach(function (k) {
                var p = document.getElementById(panel[k]);
                if (p) p.hidden = (k !== ad);
            });
            document.querySelectorAll('.by-sekme').forEach(function (b) {
                var aktif = b.getAttribute('data-sekme') === ad;
                b.classList.toggle('aktif', aktif);
                b.setAttribute('aria-selected', aktif ? 'true' : 'false');
            });
            document.title = baslik[ad] || anaBaslik;
            if (hashYaz) history.replaceState(null, '', ad === 'ana' ? location.pathname : '#' + ad);
        }
        document.querySelectorAll('[data-sekme]').forEach(function (b) {
            b.addEventListener('click', function () {
                ac(b.getAttribute('data-sekme'), true);
                var nav = document.querySelector('.by-sekmeler');
                if (nav && b.classList.contains('by-sekme-geri')) nav.scrollIntoView({ behavior: 'smooth', block: 'center' });
            });
        });
        ac(location.hash.replace('#', ''), false);
        window.addEventListener('hashchange', function () { ac(location.hash.replace('#', ''), false); });
